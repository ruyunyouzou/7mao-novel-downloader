class LanguageManager(QObject):
    """全局语言管理器（单例见 ``manager()``）。"""

    changed = Signal(str)

    def __init__(self) -> None:
        super().__init__()
        self._lang: str = LANG_ZH
        self._getter: Optional[Callable[[str, Any], Any]] = None
        self._setter: Optional[Callable[[str, Any], None]] = None

    def bind_store(self, getter: Callable[[str, Any], Any],
                   setter: Callable[[str, Any], None]) -> None:
        """绑定持久化读写，并立即载入已保存的语言。"""
        self._getter = getter
        self._setter = setter
        self.load()

    def load(self) -> None:
        if self._getter is None:
            return
        try:
            code = self._getter("language", LANG_ZH)
        except Exception:  # noqa: BLE001
            code = LANG_ZH
        if code in TRANSLATIONS:
            self._lang = str(code)

    @property
    def current(self) -> str:
        return self._lang

    def set_language(self, code: str) -> None:
        if code not in TRANSLATIONS:
            return
        self._lang = code
        if self._setter is not None:
            try:
                self._setter("language", code)
            except Exception:  # noqa: BLE001
                pass
        self.changed.emit(code)

    def tr(self, key: str, **kwargs: Any) -> str:
        table = TRANSLATIONS.get(self._lang, {})
        text = table.get(key)
        if text is None:
            text = TRANSLATIONS[LANG_ZH].get(key, key)
        if kwargs:
            try:
                text = text.format(**kwargs)
            except (KeyError, ValueError, IndexError):
                pass
        return text


_manager = LanguageManager()


def manager() -> LanguageManager:
    return _manager


def tr(key: str, **kwargs: Any) -> str:
    return _manager.tr(key, **kwargs)
